"""GPU job queue on Kaggle (T4 x2 or P100), the analogue of the paper's GPU job queue.

A job = a Python script + input files. Small inputs are packed into the script itself; large ones (up to
Kaggle's dataset limits) are uploaded as a private Kaggle dataset attached to the kernel. The harness pushes it as a private Kaggle script kernel with a GPU, polls its status, and pulls
`out/` back into the task folder. Without Kaggle credentials (or in mock mode) the same job runs
locally so the pipeline never breaks.
"""
from __future__ import annotations

import base64
import io
import json
import os
import subprocess
import sys
import threading
import time
import zipfile
from pathlib import Path

from ..config import ROOT, SERVICES
from .base import ToolContext, ToolResult

MAX_EMBED = 8 * 1024 * 1024
TEMPLATES = {"surprise": ROOT / "kaggle_job" / "surprise_model.py",
             "coupling": ROOT / "kaggle_job" / "coupling_model.py",
             "teleconnection": ROOT / "kaggle_job" / "teleconnection_map.py",
             "causal": ROOT / "kaggle_job" / "causal_map.py",
             "predictability": ROOT / "kaggle_job" / "predictability_map.py"}
ANALYSIS_TEMPLATES = ("teleconnection", "causal", "predictability")
ALL_DRIVERS = ["NINO34", "SOI", "DMI", "AMO", "PDO", "NAO", "TNA", "QBO"]


def _prepare_analysis_input(ctx: ToolContext, params: dict) -> Path:
    """Pack the campaign's own tables (trust-masked standardized anomalies) and all driver indices into one npz,
    so an agent only names the target, drivers and season."""
    import hashlib

    import pandas as pd

    from ..learn import build_input

    di = json.loads((ctx.campaign_dir / "data_index.json").read_text()) if (ctx.campaign_dir / "data_index.json").exists() else {}
    names = [params.get("target")] + list(params.get("predictors") or []) + \
        [x for x in (params.get("sources") or []) if x in di]
    vars_ = [v for v in dict.fromkeys(n for n in names if n) if v in di] or list(di)
    if params.get("sources") is None and params.get("predictors") is None:
        vars_ = list(dict.fromkeys(vars_ + list(di)))  # default: every campaign variable can be a source/predictor
    key = hashlib.md5(json.dumps(sorted(vars_)).encode()).hexdigest()[:8]
    out = ctx.campaign_dir / "gpu_inputs" / f"analysis_{key}.npz"
    final = ctx.workdir / "analysis_input.npz"
    if not out.exists():
        out.parent.mkdir(exist_ok=True)
        data = {}
        for v in vars_:
            df = pd.read_csv(di[v])
            data[v] = df[df["variable"] == v] if "variable" in df else df
        trust = pd.read_csv(ctx.campaign_dir / "trust.csv") if (ctx.campaign_dir / "trust.csv").exists() else None
        build_input(data, trust, out, drivers=ALL_DRIVERS)
    import shutil as _sh

    _sh.copyfile(out, final)
    return final
_LOCAL_JOBS: dict[str, dict] = {}


def _kaggle_ready() -> bool:
    return bool(os.getenv("KAGGLE_API_TOKEN") or (SERVICES.kaggle_key and SERVICES.kaggle_username))


def _api():
    from kaggle.api.kaggle_api_extended import KaggleApi

    api = KaggleApi()
    api.authenticate()
    return api


def _username(api) -> str:
    """KAGGLE_USERNAME if set, else the account the token belongs to."""
    return SERVICES.kaggle_username or api.get_config_value("username")


def _wrap(code: str, inputs: list[Path], via_dataset: bool = False) -> str:
    """Embed synlib (and the inputs, when small) in the script. Large inputs travel as a private Kaggle dataset
    attached to the kernel instead; the script copies them from /kaggle/input into ./inputs."""
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        if not via_dataset:
            for p in inputs:
                z.write(p, f"inputs/{p.name}")
        z.write(ROOT / "synlib" / "__init__.py", "synlib/__init__.py")
    payload = base64.b64encode(buf.getvalue()).decode()
    if len(payload) > MAX_EMBED:
        raise ValueError(f"inputs too large to embed ({len(payload) / 1e6:.1f} MB > 8 MB)")
    fetch = ("import glob as _g\nos.makedirs('inputs', exist_ok=True)\n"
             "for _f in _g.glob('/kaggle/input/**/*', recursive=True):\n"
             "    if os.path.isfile(_f): shutil.copy(_f, os.path.join('inputs', os.path.basename(_f)))\n"
             "print('inputs:', sorted(os.listdir('inputs')), flush=True)\n") if via_dataset else ""
    return (
        "# Auto-generated by Synaptic: synlib (and small inputs) are embedded below.\n"
        "import base64, io, os, sys, zipfile, shutil\n"
        f"_P = '{payload}'\n"
        "zipfile.ZipFile(io.BytesIO(base64.b64decode(_P))).extractall('.')\n"
        "os.makedirs('out', exist_ok=True)\n"
        "sys.path.insert(0, os.getcwd())\n"
        "del _P\n" + fetch +
        "import atexit\n"
        "atexit.register(lambda: [shutil.rmtree(d, ignore_errors=True) for d in ('inputs', 'synlib')])\n"
        "# ---- job code ----\n" + code
    )


def _inputs_size(files: list[Path]) -> int:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for p in files:
            z.write(p, p.name)
    return len(buf.getvalue()) * 4 // 3


def _push_dataset(api, user: str, job: str, files: list[Path], jdir: Path, timeout: int = 900) -> str:
    """Upload large inputs as a private Kaggle dataset and wait until it is ready to attach."""
    import shutil as _sh

    ddir = jdir / "dataset"
    ddir.mkdir(exist_ok=True)
    for f in files:
        _sh.copyfile(f, ddir / f.name)
    slug = f"synaptic-data-{job}"
    (ddir / "dataset-metadata.json").write_text(json.dumps(
        {"title": slug, "id": f"{user}/{slug}", "licenses": [{"name": "CC0-1.0"}]}))
    api.dataset_create_new(str(ddir), public=False, quiet=True, dir_mode="zip")
    ref, t0 = f"{user}/{slug}", time.time()
    while time.time() - t0 < timeout:
        try:
            if str(api.dataset_status(ref)).lower().endswith("ready"):
                return ref
        except Exception:  # noqa: BLE001
            pass
        time.sleep(10)
    raise TimeoutError(f"Kaggle dataset {ref} not ready after {timeout}s")


def gpu_submit(ctx: ToolContext, code: str | None = None, template: str | None = None,
               inputs: list[str] | None = None, accelerator: str = "NvidiaTeslaT4",
               params: dict | None = None) -> ToolResult:
    """Submit a GPU job. Either pass `code` (reads ./inputs/<file>, writes ./out/...) or a
    `template` name: 'surprise' (sequence model that learns each region's normal behaviour and
    reports where reality surprises it most). `params` become the PARAMS dict in the script."""
    if template:
        if template not in TEMPLATES:
            return ToolResult(f"Unknown template {template}. Available: {list(TEMPLATES)}", is_error=True)
        code = TEMPLATES[template].read_text()
        if template in ANALYSIS_TEMPLATES:
            try:
                prepared = _prepare_analysis_input(ctx, params or {})
            except Exception as e:  # noqa: BLE001
                return ToolResult(f"Could not prepare the input for template {template}: {e}", is_error=True)
            inputs = [str(prepared)]
    if not code:
        return ToolResult("Pass `code` or `template`.", is_error=True)
    code = f"import json as _json\nPARAMS = _json.loads({json.dumps(json.dumps(params or {}))})\n" + code  # JSON null/true safe
    files = [ctx.resolve(i) for i in (inputs or [])]
    missing = [str(f) for f in files if not f.exists()]
    if missing:
        return ToolResult(f"Input file(s) not found: {missing}", is_error=True)
    job = f"j{int(time.time()) % 10_000_000:07d}"
    jdir = ctx.campaign_dir / "gpu_jobs" / job
    jdir.mkdir(parents=True, exist_ok=True)
    big = _inputs_size(files) > MAX_EMBED - 200_000
    kaggle = _kaggle_ready() and not ctx.mock
    if big and not kaggle:
        return ToolResult("Inputs are larger than 8 MB and no Kaggle account is configured: aggregate first "
                          "(e.g. fewer cells, annual or seasonal means, float32 npz).", is_error=True)
    dataset_ref = None
    if big:
        try:
            api0 = _api()
            dataset_ref = _push_dataset(api0, _username(api0), job, files, jdir)
        except Exception as e:  # noqa: BLE001
            return ToolResult(f"Uploading the inputs as a Kaggle dataset failed: {str(e)[:300]}. Aggregate the "
                              "inputs below 8 MB and resubmit.", is_error=True)
    (jdir / "job.py").write_text(_wrap(code, files, via_dataset=bool(dataset_ref)))
    info = {"job": job, "task": ctx.task_id, "accelerator": accelerator, "submitted": time.time(),
            "inputs": [f.name for f in files]}
    if _kaggle_ready() and not ctx.mock:
        api = _api()
        slug = f"synaptic-{job}"
        meta = {"id": f"{_username(api)}/{slug}", "title": slug, "code_file": "job.py",
                "language": "python", "kernel_type": "script", "is_private": True, "enable_gpu": True,
                "enable_internet": True, "dataset_sources": [dataset_ref] if dataset_ref else [],
                "competition_sources": [], "kernel_sources": []}
        (jdir / "kernel-metadata.json").write_text(json.dumps(meta, indent=1))
        api.kernels_push(str(jdir), acc=SERVICES.kaggle_accelerator or accelerator)
        info.update({"backend": "kaggle", "ref": meta["id"], "dataset": dataset_ref})
        where = f"Kaggle kernel {meta['id']} on {accelerator}" + (
            f" (inputs attached as private dataset {dataset_ref})" if dataset_ref else "")
    else:
        info.update({"backend": "local"})
        out_log = jdir / "log.txt"

        def run():
            with open(out_log, "w") as log:
                p = subprocess.run([sys.executable, "job.py"], cwd=jdir, stdout=log, stderr=subprocess.STDOUT)
            _LOCAL_JOBS[job]["rc"] = p.returncode

        _LOCAL_JOBS[job] = {"rc": None}
        threading.Thread(target=run, daemon=True).start()
        where = "local CPU fallback (no Kaggle credentials configured)" if not ctx.mock else "local (mock mode)"
    (jdir / "info.json").write_text(json.dumps(info))
    return ToolResult(f"Submitted GPU job {job} to {where}. Poll with gpu_status(job='{job}') and fetch "
                      f"results with gpu_fetch(job='{job}') once complete.", meta=info)


def _info(ctx: ToolContext, job: str) -> tuple[Path, dict]:
    jdir = ctx.campaign_dir / "gpu_jobs" / job
    return jdir, json.loads((jdir / "info.json").read_text())


def gpu_status(ctx: ToolContext, job: str, wait_seconds: int = 60) -> ToolResult:
    jdir, info = _info(ctx, job)
    deadline = time.time() + max(0, min(int(wait_seconds), 600))
    while True:
        if info["backend"] == "local":
            rc = _LOCAL_JOBS.get(job, {}).get("rc", "lost")
            status = "running" if rc is None else ("complete" if rc == 0 else f"error (rc={rc})")
        else:
            r = _api().kernels_status(info["ref"])
            status = str(getattr(r, "status", r)).split(".")[-1].lower()
            if getattr(r, "failure_message", None):
                status += f": {r.failure_message}"
        if status != "running" and "queued" not in status or time.time() >= deadline:
            break
        time.sleep(10)
    return ToolResult(f"job {job}: {status}")


def _kaggle_log_text(raw: str) -> str:
    """Kaggle logs are a JSON stream of {stream_name, time, data}; turn them into plain text."""
    try:
        items = json.loads(raw) if raw.strip().startswith("[") else \
            [json.loads(x.strip().lstrip(",")) for x in raw.splitlines() if x.strip().lstrip(",").startswith("{")]
        noise = ("SyntaxWarning", "NbConvertApp", "re.sub(", "nbconvert")
        return "".join(i.get("data", "") for i in items if i.get("stream_name") in ("stdout", "stderr")
                       and not any(n in i.get("data", "") for n in noise))
    except Exception:  # noqa: BLE001
        return raw


def gpu_fetch(ctx: ToolContext, job: str) -> ToolResult:
    jdir, info = _info(ctx, job)
    dest = ctx.workdir / f"gpu_{job}"
    dest.mkdir(exist_ok=True)
    if info["backend"] == "local":
        src = jdir / "out"
        files = []
        if src.exists():
            for p in src.rglob("*"):
                if p.is_file():
                    t = dest / p.relative_to(src)
                    t.parent.mkdir(parents=True, exist_ok=True)
                    t.write_bytes(p.read_bytes())
                    files.append(str(t.relative_to(ctx.workdir)))
        log = (jdir / "log.txt").read_text()[-2500:] if (jdir / "log.txt").exists() else ""
    else:
        api = _api()
        api.kernels_output(info["ref"], str(dest), force=True)
        files = [str(p.relative_to(ctx.workdir)) for p in dest.rglob("*") if p.is_file()]
        logs = [p for p in dest.glob("*.log")]
        log = _kaggle_log_text(logs[0].read_text())[-2500:] if logs else ""
    return ToolResult(f"Fetched job {job} into {dest.name}/:\n" + "\n".join(files) + f"\n--- log tail ---\n{log}",
                      files=files)
